export function isUserLocale(value: string | null | undefined): value is UserLocale {
  return value === "lo" || value === "ko" || value === "en";
}

export function normalizeUserLocale(value: string | null | undefined): UserLocale {
  return isUserLocale(value) ? value : "lo";
}

